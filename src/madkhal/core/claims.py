"""Claims register: every claim in the README, docs and UI copy, with a resolvable pointer.

Pointer kinds:

* ``url``: a public page; it must be listed in ``docs/sources_opened.yaml`` (pages that
  were actually opened, with the date), otherwise the pointer does not resolve.
* ``result``: ``results/<file>.json#/json/pointer`` into a generated results file.
* ``parameter``: a model parameter key; resolved by a callback supplied by the caller
  (the core layer cannot import the plant or estimator layers).
* ``snapshot``: ``<path inside data/nadhir_snapshot>#row=<n>`` (1 based data row) or a
  bare path for a whole file.
* ``file``: a repository file that holds the support (for example an ADR).
"""

from __future__ import annotations

import csv
import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

CLAIM_TYPES = ("SOURCED", "SUPPORTED_BY_RESULT", "ASSUMPTION", "UNVERIFIED")
POINTER_KINDS = ("url", "result", "parameter", "snapshot", "file")


@dataclass(frozen=True)
class Claim:
    id: str
    text: str
    type: str
    where: tuple[str, ...]
    kind: str
    ref: str


def load_claims(path: Path) -> list[Claim]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    out: list[Claim] = []
    seen: set[str] = set()
    for row in data["claims"]:
        cid = str(row["id"])
        if cid in seen:
            raise ValueError(f"duplicate claim id {cid}")
        seen.add(cid)
        ctype = str(row["type"])
        if ctype not in CLAIM_TYPES:
            raise ValueError(f"{cid}: type {ctype!r} not in {CLAIM_TYPES}")
        ptr = row["pointer"]
        kind = str(ptr["kind"])
        if kind not in POINTER_KINDS:
            raise ValueError(f"{cid}: pointer kind {kind!r} not in {POINTER_KINDS}")
        out.append(
            Claim(
                id=cid,
                text=str(row["text"]).strip(),
                type=ctype,
                where=tuple(str(w) for w in row.get("where", [])),
                kind=kind,
                ref=str(ptr["ref"]),
            )
        )
    return out


def load_opened_sources(path: Path) -> dict[str, dict[str, Any]]:
    if not path.is_file():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {str(s["url"]): s for s in data.get("sources", [])}


def json_pointer(doc: Any, pointer: str) -> Any:
    if pointer in ("", "/"):
        return doc
    cur = doc
    for raw in pointer.lstrip("/").split("/"):
        part = raw.replace("~1", "/").replace("~0", "~")
        if isinstance(cur, list):
            cur = cur[int(part)]
        elif isinstance(cur, dict):
            cur = cur[part]
        else:
            raise KeyError(part)
    return cur


def resolve(
    claim: Claim,
    root: Path,
    opened: dict[str, dict[str, Any]],
    parameter_exists: Callable[[str], bool] | None = None,
) -> str | None:
    """Return None when the pointer resolves, otherwise a reason."""
    ref = claim.ref
    if claim.kind == "url":
        return None if ref in opened else f"url not in docs/sources_opened.yaml: {ref}"
    if claim.kind == "file":
        return None if (root / ref).is_file() else f"missing file {ref}"
    if claim.kind == "result":
        path, _, ptr = ref.partition("#")
        p = root / path
        if not p.is_file():
            return f"missing results file {path}"
        try:
            json_pointer(json.loads(p.read_text(encoding="utf-8")), ptr)
        except (KeyError, IndexError, ValueError):
            return f"pointer {ptr} not found in {path}"
        return None
    if claim.kind == "snapshot":
        path, _, frag = ref.partition("#")
        p = root / "data" / "nadhir_snapshot" / path
        if not p.is_file():
            return f"missing snapshot file {path}"
        if frag.startswith("row="):
            n = int(frag[4:])
            with p.open(encoding="utf-8", newline="") as fh:
                rows = list(csv.reader(fh))
            if not 1 <= n < len(rows):
                return f"row {n} not in {path}"
        return None
    if claim.kind == "parameter":
        if parameter_exists is None:
            return "no parameter resolver supplied"
        return None if parameter_exists(ref) else f"unknown parameter {ref}"
    return f"unknown pointer kind {claim.kind}"


def render_markdown(claims: list[Claim]) -> str:
    lines = [
        "# Claims register",
        "",
        "Generated by `madkhal docs build` from `docs/claims.yaml`. Do not edit by hand.",
        "Every claim made in the README, the docs and the user interface copy is listed with its",
        "type and a pointer. A test fails if any pointer does not resolve.",
        "",
        "Types: SOURCED (a public page that was opened), SUPPORTED_BY_RESULT (a file produced by",
        "code in this repository), ASSUMPTION (a modelling choice, stated as such), UNVERIFIED",
        "(carried from a source that could not be confirmed).",
        "",
        "| ID | Claim | Type | Where | Pointer |",
        "|---|---|---|---|---|",
    ]
    for c in claims:
        text = c.text.replace("|", "\\|").replace("\n", " ")
        where = ", ".join(c.where)
        lines.append(f"| {c.id} | {text} | {c.type} | {where} | {c.kind}: `{c.ref}` |")
    lines.append("")
    return "\n".join(lines)
