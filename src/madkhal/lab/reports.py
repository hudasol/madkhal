"""Rendered documents that depend on model code (parameters). Pure: returns text."""

from __future__ import annotations

from madkhal.estimator import belief_parameters, draw_parameters
from madkhal.plant import default_profile

from .inputs import prior_spec


def parameter_keys() -> set[str]:
    """Every parameter key a claim may point to."""
    keys = {p.key for p in default_profile().parameters}
    keys |= {
        f"estimator.{p.key}" for p in belief_parameters(draw_parameters(prior_spec("kalba"), 50, 1))
    }
    return keys


def parameters_markdown() -> str:
    prof = default_profile()
    lines = [
        "# Parameters",
        "",
        "Generated by `madkhal docs build` from the model code. Do not edit by hand.",
        "",
        "## Hypothetical plant (`plant.*`)",
        "",
        f"{prof.description}",
        "",
        f"Evidence level of the profile: {prof.evidence_level.value}. Share of parameters that are "
        f"assumptions: {round(100 * prof.assumption_share)} percent.",
        "",
        "Role `physics`: unknown plant behaviour, sampled towards its adverse side in the decision "
        "(ADR 0007). Role `operating`: known to the operator at decision time, used at its value.",
        "",
        "| Key | Meaning | Value | Unit | Level | Source | Spread | Adverse | Role | Provenance |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for p in prof.parameters:
        lines.append(
            f"| `{p.key}` | {p.label} | {p.value:g} | {p.unit} | {p.evidence_level.value} | "
            f"{p.source.value} | {p.rel_spread:g} | {p.adverse} | {p.role} | {p.provenance} |"
        )
    lines += [
        "",
        "## Estimator (`estimator.*`), Kalba priors",
        "",
        "Posterior summaries over 400 draws (seed 7): median and 90 percent interval. Counts come",
        "from the Nadhir snapshot; the transition parameters are assumptions (ADR 0003, ADR 0005).",
        "",
        "| Key | Meaning | Median | 90 percent interval | Source | Provenance |",
        "|---|---|---|---|---|---|",
    ]
    for bp in belief_parameters(draw_parameters(prior_spec("kalba"), 400, 7)):
        v = bp.value
        lines.append(
            f"| `estimator.{bp.key}` | {bp.label} | {v.median:.4g} | {v.lo:.4g} to {v.hi:.4g} | "
            f"{bp.source.value} | {bp.provenance} |"
        )
    lines.append("")
    return "\n".join(lines)
